/** Tiny 7x7 pixel-art icons for places where an item icon doesn't fit or doesn't exist. */
public enum Glyphs {
    BLOCK(".......", ".#####.", ".#####.", ".#####.", ".#####.", ".#####.", "......."),
    LINE("......#", ".....#.", "....#..", "...#...", "..#....", ".#.....", "#......"),
    FLOOR(".......", ".......", ".......", "#######", "#######", ".......", "......."),
    WALL("..###..", "..###..", "..###..", "..###..", "..###..", "..###..", "..###.."),
    BOX("..#####", ".#...##", "#####.#", "#...#.#", "#...#.#", "#...##.", "#####.."),
    CIRCLE("..###..", ".#...#.", "#.....#", "#.....#", "#.....#", ".#...#.", "..###.."),
    CYLINDER(".#####.", "#.....#", ".#####.", "#.....#", "#.....#", "#.....#", ".#####."),
    SPHERE("..###..", ".##..#.", "###..##", "#######", "#######", ".#####.", "..###.."),
    DOME(".......", ".......", "..###..", ".#...#.", "#.....#", "#.....#", "#######"),
    PYRAMID(".......", ".......", "...#...", "..###..", ".#####.", "#######", "......."),
    CONE("...#...", "...#...", "..###..", "..###..", ".#####.", ".#####.", "#######"),
    TORUS(".......", ".#####.", "##...##", "#.....#", "##...##", ".#####.", "......."),
    ARCH("#######", "#######", "##...##", "#.....#", "#.....#", "#.....#", "#.....#"),
    BRIDGE("#.#.#.#", "#######", "#######", "..#.#..", "..#.#..", "..#.#..", "......."),
    STAIRS("......#", ".....##", "....###", "...####", "..#####", ".######", "#######"),
    SPIRAL("#######", "#.....#", "#.###.#", "#.#.#.#", "#.#...#", "#.#####", "#......"),
    VEIN("##.....", "##.##..", "...##..", ".....##", "..##.##", "..##...", "......."),
    HOLE("#.....#", "#.....#", "#.....#", "##...##", ".#####.", ".......", "......."),
    HEART(".##.##.", "#######", "#######", ".#####.", "..###..", "...#...", "......."),
    FOOD("....##.", "...####", "..####.", ".####..", "##.#...", "##.....", "......."),
    GEAR("..#.#..", ".#####.", "##...##", ".#...#.", "##...##", ".#####.", "..#.#.."),
    CROSS("#.....#", ".#...#.", "..#.#..", "...#...", "..#.#..", ".#...#.", "#.....#"),
    PLUS("...#...", "...#...", "...#...", "#######", "...#...", "...#...", "...#..."),
    MINUS(".......", ".......", ".......", "#######", ".......", ".......", "......."),
    ROTATE("..###..", ".#...#.", "#.....#", "#...###", "#....#.", ".#.....", "..###.."),
    MIRROR("...#...", "#..#..#", "##.#.##", "###.###", "##.#.##", "#..#..#", "...#..."),
    UNDO("..#....", ".##....", "#######", ".##...#", "..#...#", "......#", "..####."),
    STOP(".#####.", "#######", "#######", "#######", "#######", "#######", ".#####."),
    EYE(".......", "..###..", ".#...#.", "#..#..#", ".#...#.", "..###..", "......."),
    FOLDER(".......", "###....", "#######", "#.....#", "#.....#", "#######", "......."),
    PAUSE(".......", ".##.##.", ".##.##.", ".##.##.", ".##.##.", ".##.##.", "......."),
    PLAY(".#.....", ".##....", ".###...", ".####..", ".###...", ".##....", ".#....."),
    TOP("#######", ".......", "...#...", "..###..", ".#####.", "...#...", "...#..."),
    LIST("#.#####", ".......", "#.#####", ".......", "#.#####", ".......", "#.#####"),
    HELP("..###..", ".#...#.", ".....#.", "....#..", "...#...", ".......", "...#..."),
    WRENCH(".....##", "....##.", "...###.", "..###..", ".###...", "###....", "##.....");

    private final String[] rows;

    Glyphs(String... rows) {
        this.rows = rows;
    }

    public static final int SIZE = 7;

    public void draw(DrawContext ctx, int x, int y, int color) {
        for (int j = 0; j < this.rows.length; j++) {
            String row = this.rows[j];
            int run = -1;
            for (int i = 0; i <= row.length(); i++) {
                boolean on = i < row.length() && row.charAt(i) == '#';
                if (on && run < 0) {
                    run = i;
                } else if (!on && run >= 0) {
                    // Draw horizontal runs as one rectangle.
                    ctx.fill(x + run, y + j, x + i, y + j + 1, color);
                    run = -1;
                }
            }
        }
    }
}
